-- Книга для читалки, разобранная один раз при загрузке.
--
-- Библиотека только пополняется: файл книги не меняется никогда (на каждую
-- загрузку новый id), значит и разбор не меняется. Разбирать epub на каждое
-- открытие — это распаковывать zip и обходить xml ради одного и того же
-- результата.
--
-- Отдельной таблицей и text, а не колонкой в books и не jsonb: select по books
-- не должен тащить всю книгу, а jsonb пришлось бы разбирать при чтении и
-- собирать при выдаче — здесь строка уходит в ответ как есть. Большие значения
-- Postgres и так сжимает (TOAST).
--
-- Оригинал остаётся в book_files: с него отдаётся /downloadOne, и из него
-- документ пересобирается, если разбор поумнеет. Тогда достаточно
-- `delete from book_docs` — /read соберёт заново при первом открытии.
create table book_docs (
    book_id uuid primary key references books (id) on delete cascade,
    doc     text not null
);

-- Картинки книги отдельными строками, а не data-URI внутри разбора.
--
-- Иллюстрированная книга — это сотня сканов по два мегабайта: в один ответ
-- читалки они не влезают ни в каком виде, а тому, кто читает текст, они
-- и не нужны. Поэтому в разборе остаётся ссылка `img/N`, а байты лежат тут
-- и отдаются по одной штуке, когда читалка до них дошла.
--
-- Это сжатая версия: длинная сторона не больше 1600 px, jpeg 78. Оригинал
-- никуда не девается — он в book_files, и /downloadOne отдаёт книгу ровно
-- такой, какой её загрузили.
create table book_images (
    book_id uuid not null references books (id) on delete cascade,
    idx     integer not null,
    mime    text not null,
    data    bytea not null,
    primary key (book_id, idx)
);

-- Книга с картинками, ради которых её и открывают: сканы, иллюстрации,
-- комиксы. Читалка по этому флагу показывает переключатель «с картинками —
-- только текст», остальным книгам он не нужен.
alter table books add column illustrated boolean not null default false;
